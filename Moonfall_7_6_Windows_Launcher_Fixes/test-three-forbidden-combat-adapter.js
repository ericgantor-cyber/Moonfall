'use strict';
const assert=require('node:assert/strict');
const {createEncounter,encounterTick}=require('./three-forbidden-encounter');
const {createCombatAdapter,consumeEvents,resolveHit}=require('./three-forbidden-combat-adapter');
const arena={x:0,y:0,width:1000,height:700};
const boss=createEncounter(100),adapter=createCombatAdapter(arena);
const player={x:500,y:350};
let events=encounterTick(boss,20,0);
let results=consumeEvents(adapter,events,player,0);
assert.equal(results.filter(e=>e.type==='warning').length,3);
const originalCurse=adapter.pending.get('silencing-curse').shapes[0];
assert.equal(originalCurse.cx,500);
assert.equal(originalCurse.cy,350);
events=encounterTick(boss,20,30);
results=consumeEvents(adapter,events,{x:900,y:600},30);
assert.equal(results[0].id,'shadow-wing-strike');
assert.equal(resolveHit(results[0],{x:500,y:350}).hit,true);
assert.equal(resolveHit(results[0],{x:950,y:650}).hit,false);
assert.equal(resolveHit(results[0],{x:579,y:350,radius:16}).hit,true,'wing lane catches player hitbox edge');
assert.equal(resolveHit(results[0],{x:600,y:500,radius:10}).hit,false,'player is beyond both crossed wing lanes');
assert.throws(()=>resolveHit(results[0],{x:500,y:350,radius:-1}),RangeError);
assert.equal(resolveHit({type:'attack',id:'shadow-wing-strike',shapes:[
 {shape:'circle',cx:100,cy:100,radius:8,damage:99},
 {shape:'circle',cx:500,cy:350,radius:8,damage:12}
]}, {x:500,y:350}).damage,12,'only colliding shapes contribute damage');
assert.equal(resolveHit(results[0],{x:500,y:350},{parrying:true}).parried,true);
assert.equal(resolveHit(results[0],{x:500,y:350},{dodging:true}).evaded,true);
events=encounterTick(boss,20,36);
results=consumeEvents(adapter,events,{x:900,y:600},36);
assert.equal(results[0].id,'echo-rupture');
assert.equal(resolveHit(results[0],{x:500,y:350}).hit,false);
events=encounterTick(boss,20,42);
results=consumeEvents(adapter,events,{x:900,y:600},42);
assert.equal(results[0].id,'silencing-curse');
assert.equal(results[0].shapes[0].cx,500,'curse target locked from warning');
assert.equal(results[0].shapes[0].cy,350,'curse target locked from warning');
assert.equal(resolveHit(results[0],{x:500,y:350}).damage,18);
assert.equal(resolveHit(results[0],{x:900,y:600}).hit,false);
events=encounterTick(boss,0,43);
results=consumeEvents(adapter,events,player,43);
assert.equal(results[0].type,'defeat');
assert.equal(adapter.pending.size,0);
assert.deepEqual(consumeEvents(adapter,[],player,44),[]);
assert.throws(()=>consumeEvents(adapter,[],player,42),RangeError);
console.log('PASS: Three Forbidden warning locks, collision, dodge, parry and defeat cleanup');
