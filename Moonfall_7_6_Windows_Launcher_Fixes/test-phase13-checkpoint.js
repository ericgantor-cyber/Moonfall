'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const c=require('./phase13-checkpoint-core.js');
const integ=require('./phase13-checkpoint-integration.js');
const raw={region:'city',stage:3,frame:450,player:{x:200,y:150,hp:20,maxHp:100}};
const cp=c.checkpoint(raw);
assert.deepEqual(cp,{version:1,region:'city',stage:3,x:200,y:150,hp:20,maxHp:100,at:450});
assert.equal(c.matches(cp,'city',3),true);
assert.equal(c.matches(cp,'city',2),false);
assert.equal(c.checkpoint({...raw,region:'bad'}),null);
assert.equal(c.checkpoint({...raw,player:{x:Infinity,y:10}}),null);
assert.deepEqual(c.respawn(cp,300,250),{x:200,y:150,hp:50});
const input='function loop(){pollController();tick();draw();requestAnimationFrame(loop)}';
const output=integ.patchJs(input);
assert(output.includes('mfCheckpointCapture()'));
assert.throws(()=>integ.patchJs(''),/hook mismatch/);
new vm.Script(output);
console.log('Phase 13 checkpoint capture tests: PASS');
