'use strict';
const assert=require('node:assert/strict');
const {createEncounter,encounterTick}=require('./three-forbidden-encounter');
const boss=createEncounter(100);
assert.deepEqual(encounterTick(boss,100,0).map(e=>e.id),['echo-rupture']);
assert.equal(encounterTick(boss,100,36)[0].type,'attack');
let e=encounterTick(boss,74,40);assert.equal(boss.phase,1);assert.equal(e[1].id,'silencing-curse');
e=encounterTick(boss,49,45);assert.equal(boss.phase,2);assert.equal(e[1].id,'shadow-wing-strike');
e=encounterTick(boss,24,50);assert.equal(boss.phase,3);
assert.deepEqual(e.filter(x=>x.type==='warning').map(x=>x.id),['echo-rupture','silencing-curse','shadow-wing-strike']);
assert.equal(encounterTick(boss,24,80)[0].id,'shadow-wing-strike');
assert.equal(encounterTick(boss,24,86)[0].id,'echo-rupture');
assert.equal(encounterTick(boss,24,92)[0].id,'silencing-curse');
encounterTick(boss,100,100);assert.equal(boss.phase,3);
assert.deepEqual(encounterTick(boss,0,110),[{type:'defeat',frame:110}]);
assert.deepEqual(encounterTick(boss,0,200),[]);
assert.throws(()=>encounterTick(boss,10,100),RangeError);
assert.throws(()=>createEncounter(0),RangeError);
const all=createEncounter(100);
assert.equal(encounterTick(all,20,0).filter(e=>e.type==='warning').length,3);
for(const frame of [30,36,42])assert.equal(encounterTick(all,20,frame).filter(e=>e.type==='attack').length,1);
// A temporarily full projectile budget must not discard an already warned attack.
const blocked=createEncounter(100);
assert.equal(encounterTick(blocked,100,0).filter(x=>x.type==='warning').length,1);
assert.equal(encounterTick(blocked,100,36,{canAttack:false}).filter(x=>x.type==='attack').length,0);
assert.equal(blocked.active.get('echo-rupture').fireAt,36);
assert.equal(encounterTick(blocked,100,37,{canAttack:false}).filter(x=>x.type==='warning').length,0);
assert.deepEqual(encounterTick(blocked,100,38,{canAttack:true}).map(x=>x.id),['echo-rupture']);
assert.equal(blocked.active.get('echo-rupture').nextWarning,188);
console.log('PASS: Three Forbidden independent 4-phase attack scheduler');
