'use strict';
const assert=require('node:assert/strict');
const w=require('./phase6-world-core.js');
const s=w.createWorldState();
assert.equal(w.travel(s,'city'),false);
assert.equal(w.travel(s,'foundry'),false);
w.unlockRegion(s,'foundry');
assert.equal(w.travel(s,'foundry'),true);
assert.equal(w.travel(s,'bosslands'),false);
w.markUnique(s,'defeatedBosses','boss-1');w.markUnique(s,'defeatedBosses','boss-1');
assert.equal(s.defeatedBosses.length,1);
const restored=w.restoreWorldState(JSON.stringify(s));
assert.deepEqual(restored,s);
assert.throws(()=>w.restoreWorldState('{"version":999}'),/Unsupported/);
const events=[];
const streamer=w.createRoomStreamer({limit:2,load:id=>{events.push('load:'+id);return{id}},unload:id=>events.push('unload:'+id)});
streamer.visit('a');streamer.visit('b');streamer.visit('a');streamer.visit('c');
assert.deepEqual(streamer.activeRooms(),['a','c']);
assert.deepEqual(events,['load:a','load:b','load:c','unload:b']);
streamer.clear();
assert.deepEqual(streamer.activeRooms(),[]);
const failures=[];
const failing=w.createRoomStreamer({limit:1,
 load:id=>({id}),unload:id=>{failures.push(id);if(id==='old')throw Error('blocked eviction');}});
failing.visit('old');
assert.throws(()=>failing.visit('new'),/blocked eviction/);
assert.deepEqual(failing.activeRooms(),['old'],'unload failure must not evict active room');
assert.deepEqual(failures,['old','new'],'failed loads should be released');
console.log('Phase 6 living-world core tests passed');
