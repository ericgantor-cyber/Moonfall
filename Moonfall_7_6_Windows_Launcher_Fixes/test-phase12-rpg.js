'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const core=require('./phase12-rpg-core.js');
const patch=require('./phase12-rpg-integration.js');
assert.deepEqual(core.restoreProfile(null),{version:1,level:1,xp:0,totalClears:0});
assert.equal(core.grantClear(null,1).xp,50);
assert.deepEqual(core.grantClear({level:1,xp:79},1),{version:1,level:2,xp:49,totalClears:1});
assert.equal(core.damageBonus({level:9}),2);
assert.equal(core.damageBonus({level:100}),12);
assert.equal(core.grantClear({level:99,xp:100000000},1000).level,100);
assert.equal(core.grantClear({level:1,xp:10},-1).xp,10);
assert.equal(core.restoreProfile({level:-9,xp:-55}).level,1);
const source='function reset(){} function beginStage(){} mfWorldOnStageClear();mfP11AfterClear(); function loop(){pollController();tick();draw();requestAnimationFrame(loop)}';
const output=patch.patchJs(source);
assert(output.includes('mfRpgStageClear()'));
assert(output.includes('mfRpgStageStart()'));
assert(output.includes('mfRpgBonusApplied=false'));
const html=patch.patchHtml('<b id="mfP11Hud"');
assert(html.includes('mfRpgHud'));
assert.throws(()=>patch.patchJs('x'),/hook missing/);
new vm.Script(output);
console.log('Phase 12 RPG foundation: PASS');
