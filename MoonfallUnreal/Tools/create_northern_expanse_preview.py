"""Create an isolated Northern Expanse greybox level in Unreal Editor 5.4.

Run only inside the MoonfallUnreal editor, after compiling its C++ classes:
  Tools > Execute Python Script > this file

Never changes the startup map, game mode, legacy map, saves, or characters.
Refuses to overwrite an existing preview level.
"""
import unreal

LEVEL_PATH = "/Game/NorthernExpanse/Maps/NorthernExpansePreview"
TAG = "NorthExpansePreview"


def required_class(name):
    result = getattr(unreal, name, None)
    if result is None:
        raise RuntimeError(
            "Required Moonfall C++ class %s is missing. Build MoonfallUnreal "
            "for UE5.4 and reopen the editor before running this script." % name
        )
    return result


def spawn(actor_subsystem, actor_class, position, label):
    actor = actor_subsystem.spawn_actor_from_class(
        actor_class, unreal.Vector(*position), unreal.Rotator(0.0, 0.0, 0.0)
    )
    if actor is None:
        raise RuntimeError("Could not place %s" % label)
    actor.set_actor_label(label)
    actor.set_editor_property("tags", [unreal.Name(TAG)])
    return actor


def main():
    # Validate all requirements before replacing the open editor level.
    continent_class = required_class("MoonfallNorthContinentActor")
    weather_class = required_class("MoonfallNorthWeatherActor")
    preview_game_mode = required_class("MoonfallNorthPreviewGameMode")
    actor_subsystem = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    level_subsystem = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if actor_subsystem is None or level_subsystem is None:
        raise RuntimeError("Required UE5 editor subsystems are unavailable")

    if unreal.EditorAssetLibrary.does_asset_exist(LEVEL_PATH):
        raise RuntimeError(
            "Preview map already exists at %s; refusing to overwrite it." % LEVEL_PATH
        )

    if not level_subsystem.new_level(LEVEL_PATH):
        raise RuntimeError("Could not create the preview level: " + LEVEL_PATH)
    # The normal Moonfall game mode auto-spawns the legacy arena and
    # thirty dungeons. Only this test world receives the safe override.
    world = unreal.EditorLevelLibrary.get_editor_world()
    if world is None:
        raise RuntimeError("New preview editor world is unavailable")
    settings = world.get_world_settings()
    if settings is None:
        raise RuntimeError("New preview world settings are unavailable")
    settings.set_editor_property("default_game_mode", preview_game_mode)
    if settings.get_editor_property("default_game_mode") != preview_game_mode:
        raise RuntimeError("Preview game mode override did not persist")


    # The continent and its nine connected pads/roads are generated by C++.
    # Only original, isolated greybox elements are placed. No divine bosses.
    spawn(actor_subsystem, continent_class, (0.0, 0.0, 0.0), "Northern Expanse Continent")
    weather = spawn(
        actor_subsystem, weather_class, (0.0, 0.0, 100.0),
        "Northern Expanse Weather Preview"
    )
    weather.set_editor_property("b_follow_player_province", True)
    weather.set_editor_property("b_enable_weather_preview", True)
    spawn(actor_subsystem, unreal.PlayerStart, (0.0, 0.0, 190.0), "North Preview Player Start")
    spawn(actor_subsystem, unreal.DirectionalLight, (0.0, 0.0, 1500.0), "North Preview Sun")

    if not level_subsystem.save_current_level():
        raise RuntimeError("Could not save the newly created preview map")
    unreal.log("Created isolated Northern Expanse editor preview at " + LEVEL_PATH)


if __name__ == "__main__":
    main()
