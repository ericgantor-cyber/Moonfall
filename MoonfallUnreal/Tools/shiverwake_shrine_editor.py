"""Idempotent UE5 shrine placement across all nine Northern Expanse zones.

The historical function name is retained for existing preview scripts. Only
the isolated Northern preview invokes this helper. It migrates untouched
shrine actors generated by the previous 18-on-Shiverwake preview, without
deleting any actor or changing user-authored shrines or campaign saves.
"""
import unreal
from shiverwake_shrine_layout import (
    SHRINE_SITES, LEGACY_SHIVERWAKE_SITES, validate_shrine_sites,
)

SHRINE_TAG = unreal.Name("NorthernExpansePreviewShrine")
LEGACY_SHRINE_TAG = "ShiverwakePreviewShrine"


def _position_matches(actor, expected):
    pos = actor.get_actor_location()
    return ((pos.x - expected[0]) ** 2
            + (pos.y - expected[1]) ** 2
            + (pos.z - expected[2]) ** 2) < 100.0


def install_shiverwake_shrines(actor_subsystem, shrine_class):
    """Return number of new or migrated actors; zero is safe to run again."""
    validate_shrine_sites()
    if actor_subsystem is None or shrine_class is None:
        raise RuntimeError("UE5 actor subsystem/shrine class unavailable")
    existing = {}
    for actor in unreal.EditorLevelLibrary.get_all_level_actors():
        if actor.get_class().get_name() != "MoonfallCheckpointShrine":
            continue
        shrine_id = str(actor.get_editor_property("shrine_id"))
        if shrine_id in existing:
            raise RuntimeError("Duplicate shrine ID in Northern preview: " + shrine_id)
        existing[shrine_id] = actor

    planned = {shrine_id: (label, position)
               for shrine_id, label, position in SHRINE_SITES}
    legacy = {shrine_id: (label, position)
              for shrine_id, label, position in LEGACY_SHIVERWAKE_SITES[2:]}
    migration = {}  # 16 legacy-generated actor IDs -> new zone identity.
    for index in range(2, len(LEGACY_SHIVERWAKE_SITES)):
        legacy_id, original_name, original_position = LEGACY_SHIVERWAKE_SITES[index]
        new_id, new_name, new_position = SHRINE_SITES[index]
        actor = existing.get(legacy_id)
        if actor is None:
            continue
        if new_id in existing:
            raise RuntimeError("Both old and new generated IDs exist: " + new_id)
        if (actor.get_actor_label() != original_name
                or not _position_matches(actor, original_position)
                or LEGACY_SHRINE_TAG not in [
                    str(tag) for tag in actor.get_editor_property("tags")
                ]):
            raise RuntimeError(
                "Old Shiverwake shrine was customized; refusing to move: " + legacy_id)
        migration[legacy_id] = (actor, new_id, new_name, new_position)

    # Preflight ALL actors before mutating the level. Preserve player edits:
    # a shrine with an expected ID but a moved location is never overwritten.
    for shrine_id, (label, position) in planned.items():
        actor = existing.get(shrine_id)
        if actor is not None and (
                actor.get_actor_label() != label
                or not _position_matches(actor, position)):
            raise RuntimeError("Existing Northern shrine was moved; refusing overwrite: "
                               + shrine_id)

    for shrine_id, (label, position) in planned.items():
        if shrine_id in existing or any(new_id == shrine_id
                                      for _, new_id, _, _ in migration.values()):
            continue
        for other_id, actor in existing.items():
            if other_id in planned or other_id in migration:
                continue
            p = actor.get_actor_location()
            if (p.x - position[0])**2 + (p.y - position[1])**2 < 300.0**2:
                raise RuntimeError("Authored shrine too close to " + shrine_id)

    # Rehome only those 16 exactly recognizable, generator-tagged actors.
    # Preview checkpoints are session-only, so these identities have never
    # been written to the player's original campaign slot.
    migrated = 0
    for legacy_id, (actor, new_id, name, position) in migration.items():
        actor.set_actor_location(unreal.Vector(*position), False, False)
        actor.set_editor_property("shrine_id", unreal.Name(new_id))
        actor.set_editor_property("map_display_name", unreal.Text(name))
        actor.set_editor_property("tags", [SHRINE_TAG])
        actor.set_actor_label(name)
        migrated += 1

    created = 0
    for shrine_id, (label, position) in planned.items():
        if shrine_id in existing or any(new_id == shrine_id
                                      for _, new_id, _, _ in migration.values()):
            continue
        actor = actor_subsystem.spawn_actor_from_class(
            shrine_class, unreal.Vector(*position), unreal.Rotator(0.0, 0.0, 0.0))
        if actor is None:
            raise RuntimeError("Could not place Northern shrine " + shrine_id)
        actor.set_editor_property("shrine_id", unreal.Name(shrine_id))
        actor.set_editor_property("map_display_name", unreal.Text(label))
        actor.set_editor_property("tags", [SHRINE_TAG])
        actor.set_actor_label(label)
        if str(actor.get_editor_property("shrine_id")) != shrine_id:
            raise RuntimeError("Northern shrine ID was not retained: " + shrine_id)
        created += 1
    unreal.log("Northern shrine layout: %d created, %d migrated; 2 per zone"
               % (created, migrated))
    return created + migrated
